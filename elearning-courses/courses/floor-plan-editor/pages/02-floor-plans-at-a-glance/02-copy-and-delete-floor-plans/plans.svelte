<h1>Floor plans at a glance</h1>

<h2>Copy and delete floor plans</h2>
<Accordion>
  <AccordionItem title='Copy floor plan'>
<p>Floors often repeat. <strong>Copy floor plan</strong> makes an exact copy of the plans you select and asks what to bring with it: furniture, floor transitions, doors and windows, and desks and offices. Untick the desks and offices when you want the shell of a floor and a fresh set of units.</p>
  </AccordionItem>
  <AccordionItem title='Delete a floor plan'>
<p>Deleting a floor plan also deletes <strong>every floor plan unit on it</strong> and its editor layout. Contracts and bookings that point at those units lose them. This cannot be undone — review what sits on the plan before you delete it.</p>
  </AccordionItem>
</Accordion>
<Callout type="important">
<p>Deleting a floor plan permanently removes every unit on it. Check which contracts and bookings point at those units first.</p>
</Callout>

