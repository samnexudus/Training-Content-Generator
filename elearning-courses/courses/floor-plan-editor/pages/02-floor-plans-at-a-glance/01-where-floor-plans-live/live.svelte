<h1>Floor plans at a glance</h1>

<p>In Nexudus Flow, every sellable place in your building lives on a floor plan. A <strong>floor plan</strong> is one level of one location. On it you draw walls, doors and windows, and you place the <strong>units</strong> — offices, dedicated desks, hot desks and rooms — that you assign to customers or make bookable.</p>
<p>This lesson covers where floor plans live, what the list page shows, and the two actions that save time when you have several similar floors.</p>
<h2>Where floor plans live</h2>
<p>Floor plans sit under <strong>Settings & administration › Administration › Floor plans</strong>. You need the <em>Floor plans</em> module switched on, and a role that includes the floor plan permissions. If you cannot see the page, ask an administrator to check both.</p>
