<p>The list shows your plans as cards with a preview by default; switch to the table view to see the values. The record holds the plan's name, its background image and its booking limit. A plan drawn in the editor carries an <strong>Open Floor Plan Editor</strong> action on its row — that is your way into the drawing tools covered in the next lesson.</p>

