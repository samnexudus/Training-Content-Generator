<h1>Floor Plan Editor</h1>

<p>A floor plan is one level of your location, drawn to scale in the Floor Plan Editor. It holds the units — the offices, dedicated desks, hot desks and rooms you assign to customers or make bookable — and gives them a place on a drawing, so your team and your members can see what is free and where it is.</p>

<h2>By the end of this course, you will be able to:</h2>

<ul>
  <li>Find and manage floor plans in Nexudus Flow</li>
  <li>Draw and edit a floor plan layout in the editor</li>
  <li>Link drawn areas to floor plan units and check availability</li>
</ul>

