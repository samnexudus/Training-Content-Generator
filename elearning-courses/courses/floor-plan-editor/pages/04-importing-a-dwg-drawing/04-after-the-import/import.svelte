<h1>Importing a DWG drawing</h1>

<h2>After the import</h2>
<p>The converted plan is drawn in the editor, and <strong>Show source drawing</strong> puts the original over it so you can compare. The drawing can be kept as the tracing image, which is worth doing: it stays underneath while you tidy the conversion, and you can remove it later from <strong>Reference images</strong>.</p>
<p>Then do the work the importer cannot: name the areas and turn them into units. A converted area is a shape until it is linked to a floor plan unit. Nothing is saved until you choose <strong>Save</strong> in the editor — leaving the page after applying a conversion loses it.</p>

