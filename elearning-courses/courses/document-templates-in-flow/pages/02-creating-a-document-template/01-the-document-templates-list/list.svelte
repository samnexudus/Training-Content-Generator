<h1>Creating a document template</h1>

<p>A document template lives under <strong>Sales &amp; relationships &rsaquo; Document Templates</strong>. It is a layout you write once and generate from many times: a membership agreement, a booking confirmation, a welcome letter or a proposal covering note. In this lesson you will see the templates list, the three kinds of template, and the three-step wizard that creates a new one.</p>
<h2>The Document Templates list</h2>
<p>The list opens sorted by name and shows each template&rsquo;s <strong>Template</strong> name, its <strong>Editor</strong>, what it is <strong>About</strong>, and its <strong>Location</strong>. The <strong>Editor</strong> badge says how the template is written (<strong>Designer</strong> or <strong>Classic</strong>); the <strong>About</strong> badge says what data it can see (<strong>Customer</strong>, <strong>Contract</strong>, <strong>Proposal</strong>, <strong>Booking</strong> or <strong>Not set</strong>).</p>
<Image
  src='$assets/list.png'
  alt='The Document Templates list showing the Editor and About columns'
/>
<p>The template name is not just a label: it becomes the <strong>file name</strong> of every document generated from it, so &ldquo;Membership agreement&rdquo; gives a customer a file they can recognise and &ldquo;Template 3&rdquo; does not. Two row commands are available on each template: <strong>Preview template</strong> generates a document from sample data and downloads it without touching a customer, and <strong>Copy template</strong> makes an exact copy named &ldquo;&hellip; - Copy&rdquo;. There is no versioning, so copying is how a second version starts.</p>

