<h1>Document Templates in Flow</h1>

<p>Document templates are the reusable layouts behind every contract, proposal, booking and customer document in Nexudus. You write the layout once, fill it with fields for the real values, and Nexudus generates a finished, personalised document each time you need one. This course covers creating a template and writing it in the Document Designer.</p>

<h2>By the end of this course, you will be able to:</h2>

<ul>
  <li>Create a document template and choose the right editor and data context for it</li>
  <li>Write a document in the Document Designer, inserting fields, conditions, repeats and signature lines</li>
  <li>Preview and generate documents from a template for the right kind of record</li>
</ul>

