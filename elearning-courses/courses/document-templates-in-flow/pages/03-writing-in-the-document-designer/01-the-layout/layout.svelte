<p>A document has three places text can live: the <strong>page header</strong> (repeats at the top of every page), the <strong>body</strong> (the document itself), and the <strong>page footer</strong> (repeats at the bottom of every page). Page numbers and page counts belong in the header or footer &mdash; put one in the body and it prints once, in the middle of the text.</p>

