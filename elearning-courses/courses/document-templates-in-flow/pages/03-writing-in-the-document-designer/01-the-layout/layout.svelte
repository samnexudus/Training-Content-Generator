<h1>Writing in the Document Designer</h1>

<p>The Document Designer is a word processor that knows your data. Type as you would anywhere, and where the document needs a real value &mdash; a name, a price, a date &mdash; insert a <strong>field</strong> instead of typing it. In this lesson you will learn the layout, how to insert and set up fields, how to add conditions and repeats, how to place signature lines, and how to preview and save.</p>
<h2>The layout</h2>
<p>The Designer has five areas: the <strong>header</strong> (the template name, <strong>Preview</strong>, <strong>Save</strong> and <strong>More actions</strong>); the <strong>toolbar</strong> with two tabs (<strong>Format</strong> for text, <strong>Document</strong> for the page) and <strong>Insert</strong> at the end; the <strong>outline</strong> on the left; the <strong>page</strong> in the middle; and three <strong>side tabs</strong> on the right: <strong>Fields</strong>, <strong>Selection</strong> and <strong>AI</strong>.</p>
