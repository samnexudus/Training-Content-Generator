<h1>Writing in the Document Designer</h1>

<h2>Generating a document</h2>
<p>A template becomes a real document in three places: a <strong>customer file</strong> (where signatures are collected), a <strong>proposal</strong> (the two documents it carries), or the <strong>Create document</strong> action on a customer, contract or booking. Run <strong>Create document</strong> from the record the template is about &mdash; a Contract template run from a customer has no contract to read, so the plan, price and term come out empty.</p>

